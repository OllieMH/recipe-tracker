// Generates supabase/seeds/foods.sql from the Matvaretabellen open API.
//
//   npm run seed:foods          (writes the SQL file)
//   npx supabase db query --remote --file supabase/seeds/foods.sql
//
// Source: https://www.matvaretabellen.no/api/nb/foods.json
// Credit: «Kilde: Matvaretabellen 2026. Mattilsynet. www.matvaretabellen.no»
//
// Only uses erasable TypeScript syntax so it runs with plain Node:
//   node --experimental-strip-types scripts/seed-foods.ts

import { writeFileSync, mkdirSync } from 'node:fs'

const BASE = 'https://www.matvaretabellen.no/api/nb'

interface Portion { id: string; portionUnit: string; quantity: number; unit: string }
interface ApiFood {
  foodName: string
  foodGroupId?: string
  searchKeywords?: string[]
  portions?: Portion[]
}

// Matvaretabellen portion id -> canonical unit used in this app.
// Ambiguous or non-canonical portions (porsjon, glass, kopp, pose ...) are skipped.
const UNIT_MAP: Record<string, string> = {
  dl: 'dl',
  spiseskje: 'ss',
  teskje: 'ts',
  stk: 'stk',
  skive: 'skive',
  pr_skive: 'skive',
  neve: 'neve',
  fedd: 'fedd',
  boks: 'boks',
  pakke: 'pk',
  bukett: 'bunt',
}
// Used only when the food has no plain 'stk' portion.
const STK_FALLBACK = 'stk_middels'

const q = (s: string) => `'${s.replace(/'/g, "''")}'`

async function getJson<T>(path: string): Promise<T> {
  const res = await fetch(`${BASE}/${path}`)
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`)
  return (await res.json()) as T
}

const { foods } = await getJson<{ foods: ApiFood[] }>('foods.json')
const { foodGroups } = await getJson<{ foodGroups: { foodGroupId: string; name: string }[] }>(
  'food-groups.json',
)
const groupName = new Map(foodGroups.map((g) => [g.foodGroupId, g.name]))

const foodRows: string[] = []
const measureRows: string[] = []
let id = 0

for (const f of foods) {
  id++
  const name = f.foodName.trim()
  const aliases = [...new Set((f.searchKeywords ?? []).map((k) => k.trim().toLowerCase()).filter(Boolean))]
  const category = f.foodGroupId ? groupName.get(f.foodGroupId) : undefined
  foodRows.push(
    `(${id}, ${q(name)}, ${aliases.length ? `array[${aliases.map(q).join(',')}]::text[]` : `'{}'::text[]`}, ${category ? q(category) : 'null'}, 'mattilsynet')`,
  )

  const byUnit = new Map<string, number>()
  for (const p of f.portions ?? []) {
    if (p.unit !== 'g' || !(p.quantity > 0)) continue
    const unit = UNIT_MAP[p.id]
    if (unit && !byUnit.has(unit)) byUnit.set(unit, p.quantity)
  }
  if (!byUnit.has('stk')) {
    const fb = (f.portions ?? []).find((p) => p.id === STK_FALLBACK && p.quantity > 0)
    if (fb) byUnit.set('stk', fb.quantity)
  }
  for (const [unit, grams] of byUnit) {
    measureRows.push(`(${id}, ${q(unit)}, ${grams}, 'mattilsynet')`)
  }
}

const sql = `-- Generated by scripts/seed-foods.ts. Do not edit by hand.
-- Source: Matvaretabellen (Mattilsynet), https://www.matvaretabellen.no/api/nb/foods.json
-- Skips itself if foods already exist. To re-seed: delete from public.foods where source = 'mattilsynet';
do $seed$
begin
  if exists (select 1 from public.foods where source = 'mattilsynet') then
    raise notice 'foods already seeded, skipping';
    return;
  end if;

  insert into public.foods (id, name_no, aliases, category, source) overriding system value values
${foodRows.join(',\n')};

  insert into public.food_measures (food_id, unit, grams, source) values
${measureRows.join(',\n')};

  perform setval(pg_get_serial_sequence('public.foods', 'id'), (select max(id) from public.foods));
end
$seed$;
`

mkdirSync('supabase/seeds', { recursive: true })
writeFileSync('supabase/seeds/foods.sql', sql, 'utf8')
console.log(`foods: ${foodRows.length}, measures: ${measureRows.length}`)
